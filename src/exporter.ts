import type { Coverage } from "./coverage";
import type { QuizResult, SummaryResult } from "./ai";

export interface ExportData {
  title: string;
  byline: string;
  coverage: Coverage;
  elapsedMs: number;
  summary: SummaryResult | null;
  quiz: QuizResult | null;
  answers: (number | null)[];
}

export function fmtTime(ms: number): string {
  const s = Math.round(ms / 1000);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

function heading(d: ExportData, id: number): string {
  return d.coverage.paras[id]?.heading || "Introduction";
}

function statsLine(d: ExportData): string {
  const s = d.coverage.stats(true);
  return `${Math.round(s.readShare * 100)}% read closely · ${s.skimmed} skimmed · ${s.skipped + s.unseen} skipped · ${fmtTime(d.elapsedMs)} reading (full read ≈ ${fmtTime(s.expectedMs)})`;
}

export function toMarkdown(d: ExportData): string {
  const lines: string[] = [];
  lines.push(`# EyeSpye reading notes: ${d.title}`, "");
  if (d.byline) lines.push(`_${d.byline}_`, "");
  lines.push(`**${new Date().toLocaleString()}** · ${statsLine(d)}`, "");

  if (d.summary && d.summary.mode !== "none") {
    const s = d.summary.summary;
    lines.push("## What you missed", "", s.headline, "");
    for (const p of s.points) {
      const where = [...new Set(p.paragraphIds.map((id) => heading(d, id)))].join(", ");
      lines.push(`- **[${p.status}]** ${p.text} _(${where})_`);
    }
    lines.push("");
    if (s.keyTerms.length) {
      lines.push("### Key terms", "");
      for (const t of s.keyTerms) lines.push(`- **${t.term}**: ${t.definition}`);
      lines.push("");
    }
    if (s.checkQuestion) lines.push("### Check yourself", "", s.checkQuestion, "");
    if (d.summary.mode === "offline") lines.push(`_Offline summary (${d.summary.reason ?? "AI unavailable"})._`, "");
  } else if (d.summary?.mode === "none") {
    lines.push("## What you missed", "", "Nothing. Every section was read closely.", "");
  }

  if (d.quiz?.questions.length) {
    const score = d.answers.filter((a, i) => a !== null && a === d.quiz!.questions[i].answerIndex).length;
    const answered = d.answers.filter((a) => a !== null).length;
    lines.push("## Quiz", "", answered ? `Score: **${score}/${d.quiz.questions.length}**` : "_Not attempted yet._", "");
    d.quiz.questions.forEach((q, i) => {
      lines.push(`**${i + 1}. ${q.question}**`, "");
      q.options.forEach((o, j) => {
        const mark = j === q.answerIndex ? "✅" : d.answers[i] === j ? "❌" : "  ";
        lines.push(`- ${mark} ${String.fromCharCode(65 + j)}. ${o}`);
      });
      lines.push("", `> ${q.explanation} _(${heading(d, q.paragraphId)})_`, "");
    });
  }
  lines.push("---", "_Generated by EyeSpye: hands-free reading that notices what you missed._");
  return lines.join("\n");
}

export function downloadMarkdown(d: ExportData): void {
  const slug = d.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 50) || "reading";
  const blob = new Blob([toMarkdown(d)], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `eyespye-${slug}.md`;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyMarkdown(d: ExportData): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(toMarkdown(d));
    return true;
  } catch {
    return false;
  }
}

/** "Save as PDF": render a clean printable page and open the browser's print dialog. */
export function printNotes(d: ExportData): void {
  const root = document.getElementById("print-root")!;
  const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
  const md = toMarkdown(d);
  // Tiny markdown → HTML for the subset toMarkdown produces.
  const html = md
    .split("\n")
    .map((l) => {
      const inline = (t: string) =>
        esc(t).replace(/\*\*(.+?)\*\*/g, "<b>$1</b>").replace(/(^|\s)_(.+?)_(?=\s|$|[.,)])/g, "$1<i>$2</i>");
      if (l.startsWith("# ")) return `<h1>${inline(l.slice(2))}</h1>`;
      if (l.startsWith("## ")) return `<h2>${inline(l.slice(3))}</h2>`;
      if (l.startsWith("### ")) return `<h3>${inline(l.slice(4))}</h3>`;
      if (l.startsWith("- ")) return `<li>${inline(l.slice(2))}</li>`;
      if (l.startsWith("> ")) return `<blockquote>${inline(l.slice(2))}</blockquote>`;
      if (l === "---") return "<hr>";
      return l.trim() ? `<p>${inline(l)}</p>` : "";
    })
    .join("\n");
  root.innerHTML = html;
  window.print();
}
